-- Аккаунт: одна строка на всю установку, а не по строке на что-нибудь.
--
-- Он не «настройка», потому что это состояние, а не выбор, и не «сессия», потому что сессия у
-- приложения одна: вошёл — значит вошёл. Отсюда и CHECK на единственную строку: две строки — это
-- два ответа на вопрос «кто я», и один из них всегда неверный.
--
-- Refresh-токен лежит здесь как есть, и это тот же компромисс, что и с секретами окружений:
-- SQLite несёт их в открытом виде, файл закрыт на 0600, а в интерфейсе об этом сказано. Хешем его
-- хранить нельзя — им надо пользоваться, а не сверять.
CREATE TABLE account (
    id            INTEGER PRIMARY KEY CHECK (id = 1),
    -- Адрес сервера, он же issuer его токенов. Хранится и тогда, когда вход не выполнен: человек
    -- его выбрал, и второй раз спрашивать нечего.
    server        TEXT    NOT NULL DEFAULT '',
    user_id       TEXT    NOT NULL DEFAULT '',
    email         TEXT    NOT NULL DEFAULT '',
    name          TEXT    NOT NULL DEFAULT '',
    -- Что аккаунту положено, как ответил сервер. Пустая строка — «не спрашивали».
    plan          TEXT    NOT NULL DEFAULT '',
    seats         INTEGER NOT NULL DEFAULT 0,
    -- Сессия этого устройства на сервере: по ней строка в списке устройств узнаётся как «это
    -- устройство», и ею же сервер отзывает вход.
    session_id    TEXT    NOT NULL DEFAULT '',
    refresh_token TEXT    NOT NULL DEFAULT '',
    signed_in_at  INTEGER NOT NULL DEFAULT 0
);
